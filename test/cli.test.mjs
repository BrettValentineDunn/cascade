import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, it } from 'node:test'
import { FULL, MINIMAL, project } from './fixture.mjs'

describe('cascade command', () => {
  it('prints help and its version without a config', () => {
    const p = project({ 'README.md': 'nothing here\n' })
    const help = p.cascade('help')
    assert.equal(help.code, 0)
    assert.match(help.out, /check-commits/)
    assert.match(p.cascade('version').out, /^\d+\.\d+\.\d+/)
  })

  it('says plainly when a command needs a config and there is none', () => {
    const p = project({ 'README.md': 'nothing here\n' })
    const r = p.cascade('impact')
    assert.equal(r.code, 2)
    assert.match(r.err, /no cascade\.config\.mjs/)
  })

  it('refuses an unknown command', () => {
    assert.equal(project(MINIMAL).cascade('nope').code, 1)
  })
})

describe('impact', () => {
  it('names the area a change touches, its surfaces, journeys, decisions and the Cascade: block', () => {
    const p = project(FULL)
    p.write({ 'src/billing/price.js': readFileSync(path.join(p.dir, 'src/billing/price.js'), 'utf8').replace('10', '12') })
    const r = p.cascade('impact')
    assert.equal(r.code, 0, r.err)
    assert.match(r.out, /Billing \[billing\]/)
    assert.match(r.out, /\[ \] help page billing/)
    assert.match(r.out, /\[ \] web\/pricing\.html/)
    assert.match(r.out, /J-01 \(importance 1\) Pay an invoice/)
    assert.match(r.out, /DECISION\(PRICE-1\) src\/billing\/price\.js:1/)
    assert.match(r.out, /only with the owner's word/)
    assert.match(r.out, /- billing: reviewed 2 surface\(s\), still true/)
    assert.match(r.out, /- decisions: kept PRICE-1/)
  })

  it('flags a web screen changed without its native pair, and the shared rule mirror', () => {
    const p = project(FULL)
    p.write({ 'src/billing/pay.js': 'export const pay = () => 1\n', 'src/shared/money.js': 'export const pence = (p) => p * 1000\n' })
    const r = p.cascade('impact', '--json')
    const report = JSON.parse(r.out)
    assert.deepEqual(report.mobile.pairs.map((x) => [x.name, x.changed]), [['Pay screen', 'web']])
    assert.deepEqual(report.mobile.sharedSources, [{ source: 'src/shared/money.js', mirrorInDiff: false }])
    assert.equal(report.mobile.release, null)
  })

  it('says a change to the native config needs a new build', () => {
    const p = project(FULL)
    p.write({ 'app/app.json': '{ "expo": { "version": "1.0.1" } }\n' })
    assert.equal(JSON.parse(p.cascade('impact', '--json').out).mobile.release, 'native-build')
  })
})

describe('check-commits', () => {
  it('refuses a commit that touches an area without its verdict, and passes one with it', () => {
    const p = project(FULL)
    const start = p.git('rev-parse', 'HEAD')
    p.commit({ 'src/billing/total.js': 'export const total = 1\n' }, 'add a total')
    const bad = p.cascade('check-commits', `${start}..HEAD`)
    assert.equal(bad.code, 1)
    assert.match(bad.err, /no Cascade: block \(it touches billing; run npx cascade impact\)/)

    p.git('reset', '-q', '--hard', start)
    p.commit({ 'src/billing/total.js': 'export const total = 1\n' },
      'add a total\n\nCascade:\n- billing: reviewed 2 surface(s), still true\n- journeys: J-01: walked on UAT\n')
    const good = p.cascade('check-commits', `${start}..HEAD`)
    assert.equal(good.code, 0, good.err)
    assert.match(good.out, /Cascade OK/)
  })

  it('needs the approver quoted when a commit rewords a decision', () => {
    const p = project(FULL)
    const start = p.git('rev-parse', 'HEAD')
    p.commit({ 'src/billing/price.js': '// DECISION(PRICE-1): prices are in pence — card fees (owner, 2026-02-01)\nexport const PRICE = 1000\n' },
      'prices in pence\n\nCascade:\n- billing: reviewed 2 surface(s), still true\n- journeys: J-01: walked on UAT\n- decisions: kept PRICE-1\n')
    const r = p.cascade('check-commits', `${start}..HEAD`)
    assert.equal(r.code, 1)
    assert.match(r.err, /removes or rewords the DECISION\(PRICE-1\) marker/)
  })

  it('fails loudly on a range that does not exist', () => {
    assert.equal(project(FULL).cascade('check-commits', 'nope..HEAD').code, 2)
  })
})

describe('decisions', () => {
  it('writes the index, and --check fails on a marker no test pins', () => {
    const p = project(FULL)
    const write = p.cascade('decisions')
    assert.equal(write.code, 0, write.err)
    const index = readFileSync(path.join(p.dir, 'docs/decisions.md'), 'utf8')
    assert.match(index, /Generated by `npx cascade decisions`/)
    assert.match(index, /\| PRICE-1 \| prices are whole pounds \|/)
    assert.equal(p.cascade('decisions', '--check').code, 0)

    p.write({ 'src/billing/tax.js': '// DECISION(TAX-1): no VAT on fees — they are exempt (owner, 2026-01-02)\n' })
    const check = p.cascade('decisions', '--check')
    assert.equal(check.code, 1)
    assert.match(check.err, /DECISION\(TAX-1\) at src\/billing\/tax\.js:1 has no test/)
  })

  it('orders the index by file in byte order, whatever order the file system lists', () => {
    const p = project(FULL)
    // NTFS lists job/ before [id]/ (it compares upper-cased names), ext4 by hash; bytes put [ first.
    p.write({
      'src/app/job/edit.js': '// DECISION(ORDER-1): one rule in two screens — kept the same (owner, 2026-01-03)\n',
      'src/app/[id]/view.js': '\n// DECISION(ORDER-1): one rule in two screens — kept the same (owner, 2026-01-03)\n',
      'tests/order.test.js': "it('DECISION(ORDER-1) holds', () => {})\n",
    })
    assert.equal(p.cascade('decisions').code, 0)
    const row = readFileSync(path.join(p.dir, 'docs/decisions.md'), 'utf8').split('\n').find((l) => l.startsWith('| ORDER-1 '))
    assert.match(row, /`src\/app\/\[id\]\/view\.js:2`<br>`src\/app\/job\/edit\.js:1`/)
  })

  it('looks up a proposed change before any code is written', () => {
    const p = project(FULL)
    p.write({ 'proposal.txt': 'Show prices with pence | src/billing/price.js\n' })
    const r = p.cascade('decisions', '--proposal', 'proposal.txt')
    assert.equal(r.code, 0, r.err)
    assert.match(r.out, /PRICE-1 \(in its files/)
    assert.match(r.out, /journeys J-01 Pay an invoice/)
  })
})

describe('sync-mobile', () => {
  it('writes the mirror, and --check fails when it drifts', () => {
    const p = project(FULL)
    assert.equal(p.cascade('sync-mobile', '--check').code, 1)
    assert.equal(p.cascade('sync-mobile').code, 0)
    const mirror = readFileSync(path.join(p.dir, 'app/shared/money.js'), 'utf8')
    assert.match(mirror, /^\/\/ GENERATED — do not edit\. Mirrored from src\/shared\/money\.js by\n\/\/ npx cascade sync-mobile/)
    assert.equal(p.cascade('sync-mobile', '--check').code, 0)
  })
})

describe('checklist', () => {
  it('reports the checklist and dry-runs an archive', () => {
    const p = project(FULL)
    const status = p.cascade('checklist', 'status')
    assert.equal(status.code, 0, status.err)
    assert.match(status.out, /CHECKLIST\.md/)
    assert.equal(p.cascade('checklist', 'archive').code, 0)
  })
})

describe('a project with only a checklist', () => {
  it('runs every command it has, with the other checks off', () => {
    const p = project(MINIMAL)
    const start = p.git('rev-parse', 'HEAD')
    p.commit({ 'src/index.js': 'export const x = 1\n' }, 'no block at all')
    const impact = p.cascade('impact', 'src/index.js')
    assert.equal(impact.code, 0, impact.err)
    assert.match(impact.out, /No feature area touched/)
    assert.match(impact.out, /- none/)
    const check = p.cascade('check-commits', `${start}..HEAD`)
    assert.equal(check.code, 0, check.err)
    assert.equal(p.cascade('checklist', 'status').code, 0)
    const doctor = p.cascade('doctor')
    assert.match(doctor.out, /on {3}checklist/)
    assert.match(doctor.out, /off {2}decisions/)
    assert.match(doctor.out, /off {2}mobile/)
    assert.equal(p.cascade('sync-mobile').code, 2)
  })
})
